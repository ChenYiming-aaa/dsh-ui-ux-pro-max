/** 落地页字段的兜底文案：`N/A - Dashboard focused` 这类不该原样露出 */
export function landingZh(raw) {
  const s = String(raw || '').trim();
  if (!s) return '—';
  if (/^N\/A/i.test(s)) {
    const tail = s.replace(/^N\/A\s*-?\s*/i, '').trim();
    const map = {
      'dashboard focused': '以仪表盘为主',
      'analytics focused': '以分析视图为主',
    };
    const note = map[tail.toLowerCase()];
    return note ? `无独立落地页 · ${note}` : '无独立落地页';
  }
  return s;
}

/** 产品类型 → 中文；查不到就退回原文 */
export function productZh(name) {
  return PRODUCT_ZH[String(name || '').trim()] || '';
}

/** 推荐模式 → 中文；逐段翻译，未收录的片段保留原文 */
export function patternZh(text) {
  const raw = String(text || '').trim();
  if (!raw) return '';
  return raw
    .split('+')
    .map((part) => {
      const t = part.trim();
      if (!t) return '';
      return PATTERN_PARTS[t.toLowerCase()] || t;
    })
    .filter(Boolean)
    .join(' + ');
}

/** 决策规则键名 → 中文 */
export function ruleKeyZh(key) {
  return RULE_KEYS[String(key || '').trim()] || '';
}

/** `style:liquid-glass` → { type: '风格', slug: 'liquid-glass' } */
export function splitRuleValue(value) {
  const s = String(value || '').trim();
  const i = s.indexOf(':');
  if (i < 0) return { type: '', slug: s };
  return { type: s.slice(0, i), slug: s.slice(i + 1) };
}
