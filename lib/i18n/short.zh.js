/**
 * short.zh.js — 中文**单字**兜底别名（L1 纯数据）
 *
 * 为什么单独一个文件、且不并入 aliases.zh.js：
 *   1. 主词典按「查询包含该词」匹配，单字键会污染所有含该字的查询
 *      （「图表」会同时命中「图」，注入无关英文词）；
 *   2. tests/check-i18n.mjs 断言主词典的源文件键数 == 运行时键数，
 *      混入第二个对象会破坏该守卫。
 *
 * 使用方式（见 query.js）：**仅当整条查询恰好是一个汉字、且主词典没有任何命中时**
 * 才启用，因此不会与多字别名叠加。
 *
 * 只收设计语境下歧义足够小的字；「表」（表单/表格）、「页」（页面/落地页）、
 * 「卡」（卡片/卡顿）这类一字多义的不收——宁可查不到，也不要给错方向。
 */
export const ZH_SHORT_ALIASES = {
  图: ['chart', 'diagram'],
  色: ['color', 'palette'],
  字: ['heading font', 'body font'],
  动: ['animation', 'motion'],
}
